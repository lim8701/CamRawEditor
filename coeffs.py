#   log+디더 **0.075** (17배). 밝은 램프 씬(DSCF1663)도 0.253 → 0.132.
# ⚠️MAX 를 낮추면 정밀도가 좋아지지만 필드가 잘린다 — DSCF1663 의 필드 최대가 6.81 이라 MAX=4
#   는 7.66 코드를 깎았다(MAX=2 는 47.7). 이론 최대 12 를 덮어야 하므로 **16 을 유지한다.**
MIST_TEX_MAX = 16.0
MIST_TEX_LOG_A = 0.01   # 로그 곡선의 무릎. 작을수록 어두운 쪽 정밀도↑(0.01 = 실측 최적 부근)
# 산란광 색 복원(Mist Color)이 죽는 휘도 바닥(카메라네이티브 scene-linear). 이 아래에서는 받는
# 픽셀의 색비가 노이즈뿐이라 복원하면 그 노이즈를 증폭한다 → 물리(산란광 그대로)로 되돌린다.
MIST_COLOR_FLOOR = 0.02

# 기타 강도 계수 (샤프닝 / HSL 믹서 / 컬러 그레이딩)
SHARPEN = 1.5           # 언샤프 마스크 강도
HSL_HUE_DEG = 30.0      # HSL 색상대 hue 시프트 최대(도)
HSL_LUM = 0.5           # HSL 휘도 조정 스케일
COLOR_GRADE = 0.5       # 컬러 그레이딩(스플릿 토닝) 강도


def mist_log_k() -> float:
    """미스트 저장 코덱의 정규화 상수 log2(1 + MAX/A). 인코드/디코드 양쪽의 단일 진실원."""
    import math
    return math.log2(1.0 + MIST_TEX_MAX / MIST_TEX_LOG_A)


